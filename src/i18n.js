const FALLBACK = 'id'

export function translate(lang, key, vars = {}) {
  const table = I18N[lang] || I18N[FALLBACK]
  let str = table[key] ?? I18N[FALLBACK][key] ?? key
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v))
  }
  return str
}
